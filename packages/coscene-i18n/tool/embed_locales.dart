// Checks the dictionaries in locales/ and embeds them in the Dart package.
//
//   dart run tool/embed_locales.dart
//
// locales/en.json is the reference. Every other language must have exactly
// the same keys and the same {placeholders} in each entry.
import 'dart:convert';
import 'dart:io';

import 'package:coscene_i18n/src/languages.dart';

final _placeholder = RegExp(r'\{\w+\}');

void main() {
  if (!File('pubspec.yaml').existsSync() || !Directory('locales').existsSync()) {
    stderr.writeln('Run this from packages/coscene-i18n.');
    exit(64);
  }
  final all = <String, Map<String, String>>{};
  final problems = <String>[];
  for (final lang in supportedLanguages) {
    final file = File('locales/${lang.code}.json');
    if (!file.existsSync()) {
      problems.add('${lang.code}: locales/${lang.code}.json is missing');
      continue;
    }
    all[lang.code] = (jsonDecode(file.readAsStringSync()) as Map<String, dynamic>).cast<String, String>();
  }
  final en = all[fallbackLanguage]!;
  for (final e in all.entries) {
    for (final key in en.keys) {
      final text = e.value[key];
      if (text == null || text.trim().isEmpty) {
        problems.add('${e.key}: missing "$key"');
        continue;
      }
      final want = _placeholder.allMatches(en[key]!).map((m) => m.group(0)).toList()..sort();
      final got = _placeholder.allMatches(text).map((m) => m.group(0)).toList()..sort();
      if (want.join() != got.join()) problems.add('${e.key}: placeholders differ in "$key"');
    }
    for (final key in e.value.keys) {
      if (!en.containsKey(key)) problems.add('${e.key}: unknown key "$key"');
    }
  }
  if (problems.isNotEmpty) {
    stderr.writeln('Dictionaries have problems, nothing embedded:');
    problems.take(40).forEach(stderr.writeln);
    exit(1);
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_locales.dart from locales/*.json. Do not edit.')
    ..writeln()
    ..writeln('const Map<String, String> localeJson = {');
  for (final e in all.entries) {
    out.writeln("  '${e.key}': r'''");
    out.writeln(jsonEncode(e.value));
    out.writeln("''',");
  }
  out.writeln('};');
  File('lib/src/generated/locales.g.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('Embedded ${all.length} languages, ${en.length} entries each.');
}
