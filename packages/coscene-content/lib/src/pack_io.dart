import 'dart:convert';
import 'dart:io';

import 'package:coscene_core/coscene_core.dart';

import 'level_pack.dart';
import 'places.dart';

const JsonEncoder _pretty = JsonEncoder.withIndent('  ');

/// Reads a pack kept as a folder: `pack.json` plus one file per place.
LevelPack readPackDirectory(String path) {
  final index = jsonDecode(File('$path/pack.json').readAsStringSync()) as Map<String, dynamic>;
  final places = <PlaceInfo>[];
  final levels = <LevelSpec>[];
  for (final name in (index['placeFiles'] as List).cast<String>()) {
    final doc = jsonDecode(File('$path/$name').readAsStringSync()) as Map<String, dynamic>;
    places.add(PlaceInfo.fromJson(doc['place'] as Map<String, dynamic>));
    for (final l in doc['levels'] as List) {
      levels.add(LevelSpec.fromJson(l as Map<String, dynamic>));
    }
  }
  return LevelPack(
    id: index['id'] as String,
    version: index['version'] as int,
    minEngineVersion: index['minEngineVersion'] as int? ?? 1,
    places: places,
    levels: levels,
  );
}

/// Writes a pack as a folder of readable JSON, one file per place.
void writePackDirectory(LevelPack pack, String path) {
  Directory(path).createSync(recursive: true);
  final files = <String>[];
  for (final place in pack.places) {
    final name = 'place-${place.number.toString().padLeft(2, '0')}.json';
    files.add(name);
    File('$path/$name').writeAsStringSync(
      '${_pretty.convert({
        'place': place.toJson(),
        'levels': [for (final l in pack.levels)
          if (l.place == place.number) l.toJson()],
      })}\n',
    );
  }
  File('$path/pack.json').writeAsStringSync(
    '${_pretty.convert({'id': pack.id, 'version': pack.version, 'minEngineVersion': pack.minEngineVersion, 'placeFiles': files})}\n',
  );
}

