// Creates the Ed25519 key pair that signs remote level packs.
//
//   dart run tool/keygen.dart
//
// The private key is written to <repo>/secrets/pack_signing_key.json, which
// is git-ignored. Keep it somewhere safe: whoever holds it can publish
// levels to every installed copy of the app. The public half is written
// into lib/src/generated/pack_key.g.dart and ships inside the app.
import 'dart:convert';
import 'dart:io';

import 'package:cryptography/cryptography.dart';

const _secretPath = '../../secrets/pack_signing_key.json';
const _generated = 'lib/src/generated/pack_key.g.dart';

Future<void> main(List<String> args) async {
  if (!File('pubspec.yaml').existsSync() || !Directory('tool').existsSync()) {
    stderr.writeln('Run this from packages/coscene-content.');
    exit(64);
  }
  final secret = File(_secretPath);
  if (secret.existsSync() && !args.contains('--force')) {
    stderr.writeln('A signing key already exists at ${secret.path}.');
    stderr.writeln('Replacing it cuts off every installed app from new packs. Pass --force to do it anyway.');
    exit(1);
  }
  final pair = await Ed25519().newKeyPair();
  final seed = await pair.extractPrivateKeyBytes();
  final public = (await pair.extractPublicKey()).bytes;
  secret
    ..createSync(recursive: true)
    ..writeAsStringSync(
      '${jsonEncode({'algorithm': 'ed25519', 'privateKey': base64Encode(seed), 'publicKey': base64Encode(public)})}\n',
    );
  File(_generated)
    ..createSync(recursive: true)
    ..writeAsStringSync('''
// GENERATED by tool/keygen.dart. Do not edit.
// Public half of the key that signs remote level packs.

const String packSigningPublicKey = '${base64Encode(public)}';
''');
  stdout.writeln('Private key: ${secret.path} (keep it secret, back it up)');
  stdout.writeln('Public key written to $_generated');
}
